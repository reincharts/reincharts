// Generates build inputs that live in the repo but are derived from other files:
//   1. data/json/*.json   compact JSON versions of the sample TSV files (used by lib/data*.ts)
//   2. components/preview/registry.generated.tsx   lazy map of every examples/*.tsx file
//   3. content/api/**   the API reference, from the TypeScript sources of every package (scripts/generate-api.mjs)
// Runs before `dev`, `build` and `typecheck`; safe to run any time (only writes when content changes).
import { tsvParse } from "d3-dsv";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

const write = (file, content) => {
    const path = join(root, file);
    if (existsSync(path) && readFileSync(path, "utf8") === content) {
        return;
    }
    writeFileSync(path, content);
    console.log(`[generate] wrote ${file}`);
};

const round = (v, digits = 2) => {
    const n = Number(v);
    if (v === "" || v === undefined || !Number.isFinite(n)) {
        return null;
    }
    const f = 10 ** digits;
    return Math.round(n * f) / f;
};

const tsv = (name) => tsvParse(readFileSync(join(root, "data", name), "utf8"));

// ------------------------------------------------------------------ data
// rows are tuples to keep the client bundle small; lib/data*.ts turns them into objects
const daily = tsv("DAILY.tsv").map((d) => [
    d.date,
    round(d.open),
    round(d.high),
    round(d.low),
    round(d.close),
    Number(d.volume),
]);
write(
    "data/json/daily.json",
    JSON.stringify({ columns: ["date", "open", "high", "low", "close", "volume"], rows: daily }),
);

const comparison = tsv("comparison.tsv").map((d) => [
    d.date,
    round(d.open),
    round(d.high),
    round(d.low),
    round(d.close),
    Number(d.volume),
    round(d.SP500Close),
    round(d.AAPLClose),
    round(d.GEClose),
]);
write(
    "data/json/comparison.json",
    JSON.stringify({
        columns: ["date", "open", "high", "low", "close", "volume", "sp500", "aapl", "ge"],
        rows: comparison,
    }),
);

const minutes = tsv("MINUTES.tsv").map((d) => [
    Number(d.date),
    round(d.open),
    round(d.high),
    round(d.low),
    round(d.close),
    Number(d.volume),
]);
write(
    "data/json/minutes.json",
    JSON.stringify({ columns: ["date", "open", "high", "low", "close", "volume"], rows: minutes }),
);

const seconds = tsv("SECONDS.tsv").map((d) => [
    Number(d.date),
    round(d.open, 3),
    round(d.high, 3),
    round(d.low, 3),
    round(d.close, 3),
]);
write("data/json/seconds.json", JSON.stringify({ columns: ["date", "open", "high", "low", "close"], rows: seconds }));

// ------------------------------------------------------------------ example registry
const names = readdirSync(join(root, "examples"))
    .filter((f) => f.endsWith(".tsx") && !f.startsWith("_"))
    .map((f) => f.slice(0, -4))
    .sort();

const registry = `"use client";
// Generated by scripts/generate.mjs from the files in examples/. Do not edit by hand.
import dynamic from "next/dynamic";
import type { ComponentType } from "react";
import { ChartSkeleton } from "./chart-skeleton";

const load = (importer: () => Promise<{ default: ComponentType }>) => dynamic(importer, { ssr: false, loading: ChartSkeleton });

export const examples: Record<string, ComponentType> = {
${names.map((n) => `    ${JSON.stringify(n)}: load(() => import("@/examples/${n}")),`).join("\n")}
};
`;
write("components/preview/registry.generated.tsx", registry);

// ------------------------------------------------------------------ API reference
await import("./generate-api.mjs");
