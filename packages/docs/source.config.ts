import { pageSchema } from "fumadocs-core/source/schema";
import { defineConfig, defineDocs } from "fumadocs-mdx/config";
import { z } from "zod";

/** Optional cross-section links shown under the page description ("Examples", "API reference", "Docs"). */
const schema = pageSchema.extend({
    examples: z.string().optional(),
    api: z.string().optional(),
    docs: z.string().optional(),
});

/** /docs: high-level guides. */
export const docs = defineDocs({ dir: "content/docs", docs: { schema } });

/** /examples: live examples, basic and advanced. */
export const examples = defineDocs({ dir: "content/examples", docs: { schema } });

/** /api: generated by scripts/generate-api.mjs from the TypeScript sources of every package. */
export const api = defineDocs({ dir: "content/api", docs: { schema } });

export default defineConfig();
